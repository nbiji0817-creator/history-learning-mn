-- ============================================================================
--  0008 — «Түүхэн хослол» тоглоомыг «Тулалдааны тактик»-аар солих
-- ============================================================================
--
--  «Түүхэн хослол» (memory) бол хөзөр эргүүлж хос олох тоглоом байсан.
--  Түүхийн агуулгатай сул холбоотой — хос олоход түүхэн мэдлэг бараг
--  хэрэггүй, зөвхөн санах ой шалгадаг. Оронд нь монголын жинхэнэ
--  цэргийн тактикийг хөдөлгөөнт зураглалаар үзүүлэх симуляц нэмж байна.
--
--  ⚠️ `game_scores` нь `games.slug`-д `on delete cascade`-ээр холбогдсон
--  тул memory тоглоомын оноо мөн устана. Энэ нь зориудын — тоглоом
--  байхгүй болсны дараа түүний оноо утгагүй.
--
--  Дахин ажиллуулж болно.
-- ============================================================================

insert into public.games (slug, kind, title, description, icon, grades, difficulty, playable, xp)
values (
  'battle-tactics',
  'battle_tactics',
  'Тулалдааны тактик',
  'Түүхэн тулалдаанд монголын жинхэнэ тактикаас сонго. Шийдвэрээ хөдөлгөөнт зураглалаар хараад, түүхэнд юу болсныг мэдэж ав.',
  '⚔️',
  '{6,7,8,9,10,11,12}',
  'medium',
  true,
  40
)
on conflict (slug) do update
set kind = excluded.kind,
    title = excluded.title,
    description = excluded.description,
    icon = excluded.icon,
    grades = excluded.grades,
    difficulty = excluded.difficulty,
    playable = true,
    xp = excluded.xp;

delete from public.games where slug = 'memory';
