/**
 * Нэгдсэн тайлбар толь.
 * Гараар бичсэн нэр томьёо + 10-р ангийн толиос нүүлгэсэн нэр томьёо.
 * Нэр давхцвал гараар бичсэн тайлбарыг нь давуу гэж үзнэ.
 */
export const glossaryTerms: GlossaryTerm[] = (() => {
  const seen = new Map<string, GlossaryTerm>();
  for (const term of [...curatedGlossary, ...textbookGlossary]) {
    const key = term.term.trim().toLowerCase();
    if (!seen.has(key)) seen.set(key, term);
  }
  return Array.from(seen.values());
})();

export const glossaryCategories = Array.from(
  new Set(glossaryTerms.map((term) => term.category)),
);
